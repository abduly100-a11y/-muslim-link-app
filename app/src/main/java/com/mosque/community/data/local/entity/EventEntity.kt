package com.mosque.community.data.local.entity

import androidx.room.Entity
import androidx.room.PrimaryKey
import com.mosque.community.data.models.Event
import com.mosque.community.data.models.RsvpState

@Entity(tableName = "events")
data class EventEntity(
    @PrimaryKey val id: String,
    val mosqueId: String,
    val mosqueName: String,
    val mosqueImageUrl: String,
    val title: String,
    val description: String,
    val posterUrl: String,
    val timestampEpochMillis: Long,
    val endTimestampEpochMillis: Long,
    val dateMonth: String,
    val dateDay: String,
    val dayOfWeek: String,
    val dateLabel: String,
    val fullDate: String,
    val timeLabel: String,
    val location: String,
    val address: String,
    val category: String,
    val isTonight: Boolean,
    val isThisWeek: Boolean,
    val isBookmarked: Boolean,
    val rsvpState: String,
    val reminderEnabled: Boolean,
    val attendeeCount: Int,
    val capacity: Int?,
    val registrationRequired: Boolean,
    val cost: Double?,
    val isOnline: Boolean,
    val language: String,
    val speakerIds: String,
    val speakerNames: String,
    val tags: String,
    val isMosqueFollowed: Boolean
) {
    fun toEvent(): Event = Event(
        id = id,
        mosqueId = mosqueId,
        mosqueName = mosqueName,
        mosqueImageUrl = mosqueImageUrl,
        title = title,
        description = description,
        posterUrl = posterUrl,
        timestampEpochMillis = timestampEpochMillis,
        endTimestampEpochMillis = endTimestampEpochMillis,
        dateMonth = dateMonth,
        dateDay = dateDay,
        dayOfWeek = dayOfWeek,
        dateLabel = dateLabel,
        fullDate = fullDate,
        timeLabel = timeLabel,
        location = location,
        address = address,
        category = category,
        isTonight = isTonight,
        isThisWeek = isThisWeek,
        isBookmarked = isBookmarked,
        rsvpState = try { RsvpState.valueOf(rsvpState) } catch (e: Exception) { RsvpState.NOT_ATTENDING },
        reminderEnabled = reminderEnabled,
        attendeeCount = attendeeCount,
        capacity = capacity,
        registrationRequired = registrationRequired,
        cost = cost,
        isOnline = isOnline,
        language = language,
        speakerIds = if (speakerIds.isBlank()) emptyList() else speakerIds.split("||"),
        speakerNames = if (speakerNames.isBlank()) emptyList() else speakerNames.split("||"),
        tags = if (tags.isBlank()) emptyList() else tags.split("||"),
        isMosqueFollowed = isMosqueFollowed
    )

    companion object {
        fun fromEvent(event: Event): EventEntity = EventEntity(
            id = event.id,
            mosqueId = event.mosqueId,
            mosqueName = event.mosqueName,
            mosqueImageUrl = event.mosqueImageUrl,
            title = event.title,
            description = event.description,
            posterUrl = event.posterUrl,
            timestampEpochMillis = event.timestampEpochMillis,
            endTimestampEpochMillis = event.endTimestampEpochMillis,
            dateMonth = event.dateMonth,
            dateDay = event.dateDay,
            dayOfWeek = event.dayOfWeek,
            dateLabel = event.dateLabel,
            fullDate = event.fullDate,
            timeLabel = event.timeLabel,
            location = event.location,
            address = event.address,
            category = event.category,
            isTonight = event.isTonight,
            isThisWeek = event.isThisWeek,
            isBookmarked = event.isBookmarked,
            rsvpState = event.rsvpState.name,
            reminderEnabled = event.reminderEnabled,
            attendeeCount = event.attendeeCount,
            capacity = event.capacity,
            registrationRequired = event.registrationRequired,
            cost = event.cost,
            isOnline = event.isOnline,
            language = event.language,
            speakerIds = event.speakerIds.joinToString("||"),
            speakerNames = event.speakerNames.joinToString("||"),
            tags = event.tags.joinToString("||"),
            isMosqueFollowed = event.isMosqueFollowed
        )
    }
}
